// Static asset reference audit (read-only; deletes nothing). Follow-up to #52.
//   node tools/audit-assets.mjs            -> print a summary
//   node tools/audit-assets.mjs --markdown -> print a Markdown report (docs/ASSET_AUDIT.md)
//
// For every tracked media/icon file it searches every tracked text source for the
// file's repo path or basename, then classifies it:
//   referenced   - named by at least one source file (HTML, JS, CSS, sw.js, ...)
//   external     - not named in code, but known to be used from outside the repo
//                  (DNS BIMI record, email templates, browser auto-requests, ...)
//   candidate    - named nowhere. NOT proof of dead weight: may be loaded by a
//                  dynamically built URL, by Shopify, or by an old installed PWA.
// Docs (*.md) are reported separately: a mention in a handoff is not a use.
import fs from 'fs';
import path from 'path';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tracked = execFileSync('git', ['ls-files', '-z'], { cwd: ROOT, encoding: 'utf8' })
  .split('\0').filter(Boolean);

const MEDIA = /\.(png|jpe?g|gif|webp|avif|svg|ico|mp4|webm|mov|mp3|woff2?|ttf|otf)$/i;
const ASSET_DIRS = ['img/', 'images/', 'video/', 'assets/'];
const isAsset = f => MEDIA.test(f) && (ASSET_DIRS.some(d => f.startsWith(d)) || !f.includes('/'));
const assets = tracked.filter(isAsset).sort();

// Text sources searched for references. Vendored libraries and the emoji set are
// skipped (they never reference site assets); tests/fixtures count as non-runtime.
const TEXT = /\.(html?|m?js|cjs|css|json|py|toml|txt|xml|md)$|(^|\/)_headers$|(^|\/)_redirects$/i;
const SKIP = /^(emoji|vendor|node_modules)\//;
const sources = tracked.filter(f => TEXT.test(f) && !SKIP.test(f) && fs.statSync(path.join(ROOT, f)).size < 5e6);
const kindOf = f => f.endsWith('.md') ? 'doc'
  : /^tools\/(test-|fixtures\/)/.test(f) ? 'test'
  : 'code';
const text = new Map(sources.map(f => [f, fs.readFileSync(path.join(ROOT, f), 'utf8')]));

// Used from outside the repository's code, so absence of a code reference is expected.
const EXTERNAL = [
  [/^favicon\.(ico|png|svg)$/, 'browsers request /favicon.* automatically'],
  [/^apple-touch-icon(-precomposed)?\.png$/, 'iOS requests /apple-touch-icon*.png automatically'],
  [/^img\/bimi-logo/, 'BIMI logo: referenced by the DNS BIMI TXT record, not by code'],
  [/^img\/email-logo/, 'email logo: may be referenced by Shopify / Worker email templates by absolute URL'],
  [/^img\/og/, 'Open Graph image: may be cached by social sites and linked from Shopify'],
];

const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const rows = assets.map(a => {
  const base = path.posix.basename(a);
  // Match the basename as a whole token (not as a suffix of a longer name).
  const re = new RegExp(`(^|[^A-Za-z0-9_-])${esc(base)}($|[^A-Za-z0-9_.-]|\\.(?![A-Za-z0-9]))`);
  const refs = { code: [], test: [], doc: [] };
  for (const [f, t] of text) if (f !== a && re.test(t)) refs[kindOf(f)].push(f);
  const ext = EXTERNAL.find(([r]) => r.test(a));
  const status = refs.code.length ? 'referenced' : ext ? 'external' : 'candidate';
  return { a, size: fs.statSync(path.join(ROOT, a)).size, refs, status, note: ext ? ext[1] : '' };
});

// Version-pinned names: a "-v2" / "-fresh" sibling often supersedes the original.
const families = new Map();
for (const r of rows) {
  const stem = r.a.replace(/(-v\d+|-fresh|-precomposed)?(\.[a-z0-9]+)$/i, '$2');
  if (!families.has(stem)) families.set(stem, []);
  families.get(stem).push(r.a);
}

const kb = n => (n / 1024).toFixed(n < 10240 ? 1 : 0) + ' KB';
const by = s => rows.filter(r => r.status === s);
const total = list => list.reduce((s, r) => s + r.size, 0);

if (process.argv.includes('--markdown')) {
  const out = [];
  const date = new Date().toISOString().slice(0, 10);
  out.push(`# Static asset reference audit — ${date}`, '',
    'Generated by `node tools/audit-assets.mjs --markdown` (read-only; deletes nothing). Follow-up to #52.', '',
    `Scanned ${assets.length} tracked media/icon files in \`img/\`, \`images/\`, \`video/\`, \`assets/\` and the repo root against ${sources.length} tracked text sources (HTML, built and source JS/CSS, \`sw.js\`, \`webapp.json\`, \`_headers\`, \`functions/\`, \`worker/\`, build scripts). \`emoji/\` and \`vendor/\` are out of scope.`, '',
    '| Status | Files | Size |', '|---|---:|---:|',
    ...['referenced', 'external', 'candidate'].map(s => `| ${s} | ${by(s).length} | ${kb(total(by(s)))} |`), '',
    '**A "candidate" is not proof of dead weight.** Before removing any file, also check: URLs built at runtime (template strings, `+` concatenation), Shopify product/theme content, email templates in the Worker repo, the live `_headers`/DNS, and Home Screen web apps installed with older icon/splash URLs. Removals belong in their own PR with user approval.', '');
  out.push('## Unreferenced candidates', '');
  if (!by('candidate').length) out.push('None.', '');
  else {
    out.push('| File | Size | Mentioned only in |', '|---|---:|---|');
    for (const r of by('candidate')) out.push(`| \`${r.a}\` | ${kb(r.size)} | ${[...r.refs.test, ...r.refs.doc].map(f => '`' + f + '`').join(', ') || '—'} |`);
    out.push('');
  }
  out.push('## Used outside the code (keep)', '', '| File | Size | Why |', '|---|---:|---|',
    ...by('external').map(r => `| \`${r.a}\` | ${kb(r.size)} | ${r.note} |`), '');
  const fam = [...families.values()].filter(v => v.length > 1);
  if (fam.length) {
    out.push('## Versioned siblings', '', 'Same name with a version/variant suffix. Check whether the older one is still needed.', '');
    for (const v of fam) out.push('- ' + v.map(f => `\`${f}\` (${rows.find(r => r.a === f).status})`).join(' · '));
    out.push('');
  }
  out.push('## Referenced', '', '<details><summary>' + by('referenced').length + ' files</summary>', '', '| File | Size | First code reference |', '|---|---:|---|',
    ...by('referenced').map(r => `| \`${r.a}\` | ${kb(r.size)} | \`${r.refs.code[0]}\`${r.refs.code.length > 1 ? ` +${r.refs.code.length - 1}` : ''} |`),
    '', '</details>', '');
  process.stdout.write(out.join('\n'));
} else {
  for (const s of ['referenced', 'external', 'candidate']) console.log(`${s.padEnd(11)} ${String(by(s).length).padStart(4)} files  ${kb(total(by(s)))}`);
  for (const r of by('candidate')) console.log(`  candidate  ${r.a}  (${kb(r.size)})`);
}
